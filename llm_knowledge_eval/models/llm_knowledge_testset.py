import logging

from odoo import _, api, fields, models

_logger = logging.getLogger(__name__)


class LLMKnowledgeTestset(models.Model):
    _name = "llm.knowledge.testset"
    _description = "RAG Test Set"
    _inherit = ["mail.thread"]
    _order = "id desc"

    name = fields.Char(required=True, tracking=True)
    collection_id = fields.Many2one(
        "llm.knowledge.collection",
        string="Knowledge Collection",
        required=True,
        ondelete="cascade",
        tracking=True,
        help="The knowledge collection this test set's questions were derived from.",
    )
    resource_ids = fields.Many2many(
        "llm.resource",
        string="Source Documents",
        help="Optional subset of the collection's resources this test set was "
        "generated from. Leave empty if it covers the whole collection.",
    )
    description = fields.Text()
    source = fields.Char(
        string="Generated By",
        tracking=True,
        help="Free-text label identifying which tool produced this test set, "
        "e.g. 'ragas' or 'manual'. This module has no dependency on any "
        "specific generator tool.",
    )
    state = fields.Selection(
        [
            ("draft", "Draft"),
            ("generating", "Generating"),
            ("ready", "Ready"),
            ("failed", "Failed"),
        ],
        default="draft",
        required=True,
        tracking=True,
    )
    item_ids = fields.One2many(
        "llm.knowledge.testset.item", "testset_id", string="Test Cases"
    )
    item_count = fields.Integer(compute="_compute_item_count")
    active = fields.Boolean(default=True)

    @api.depends("item_ids")
    def _compute_item_count(self):
        for testset in self:
            testset.item_count = len(testset.item_ids)

    def action_view_items(self):
        self.ensure_one()
        return {
            "name": _("Test Cases"),
            "type": "ir.actions.act_window",
            "res_model": "llm.knowledge.testset.item",
            "view_mode": "list,form",
            "domain": [("testset_id", "=", self.id)],
            "context": {"default_testset_id": self.id},
        }
